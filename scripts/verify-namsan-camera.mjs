// 남산 휴대폰 카메라·쌍안경 이름표 점검(11-21). node scripts/verify-namsan-camera.mjs → artifacts/namsan-camera/. 실패 시 종료 코드 1.
import {chromium} from '@playwright/test';
import {mkdirSync} from 'node:fs';
const dir='artifacts/namsan-camera';mkdirSync(dir,{recursive:true});
const {createServer}=await import('vite');const port=5343;
const vite=await createServer({server:{port,host:'127.0.0.1',strictPort:true},logLevel:'warn'});await vite.listen();
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const sl=ms=>new Promise(r=>setTimeout(r,ms));let fail=0;
const check=(n,ok,d)=>{console.log(ok?'✔':'✘',n,JSON.stringify(d??'').slice(0,200));if(!ok)fail++;};
const ctx=await browser.newContext({viewport:{width:1280,height:800},acceptDownloads:true});
await ctx.addInitScript(()=>{localStorage.clear();localStorage.setItem('gwanak-sound-enabled','false');});
const p=await ctx.newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));
await p.goto(`http://127.0.0.1:${port}/hiking/namsan/?time=13:00&weather=clear`);
await p.waitForFunction('window.namsan?.started',null,{timeout:180000});await sl(1000);
const ev=f=>p.evaluate(f);
check('휴대폰 단추 보임',await ev(()=>{const b=document.querySelector('#phone');return !!b&&!b.hidden&&b.getBoundingClientRect().width>0;}));
await p.evaluate(()=>window.dispatchEvent(new CustomEvent('hiking:command',{detail:{id:'phone'}})));await sl(800);
check('휴대폰 모드 켜짐',(await ev(()=>window.namsan.status().gadget))==='phone');
await p.screenshot({path:`${dir}/phone.png`});
const dl=p.waitForEvent('download',{timeout:8000}).catch(()=>null);
await p.evaluate(()=>window.dispatchEvent(new CustomEvent('hiking:command',{detail:{id:'shutter'}})));
const d=await dl;check('셔터 → 사진 저장',!!d&&/^남산-/.test(d.suggestedFilename()),d?.suggestedFilename());
await p.evaluate(()=>window.dispatchEvent(new CustomEvent('hiking:command',{detail:{id:'selfie'}})));await sl(900);
await p.screenshot({path:`${dir}/selfie.png`});
await p.evaluate(()=>window.dispatchEvent(new CustomEvent('hiking:command',{detail:{id:'gadget-off'}})));
await p.evaluate(()=>window.dispatchEvent(new CustomEvent('hiking:command',{detail:{id:'binoculars'}})));await sl(900);
// status().interact.bino는 화면 안 이름표(labels) 이름만 준다. 출발 지점 방향에 따라 명소가 화면 밖(방위 띠·「n° 오른쪽」 안내)에만 있을 수 있어 화면 요소로 본다
const b=await ev(()=>({...window.namsan.status().interact?.bino,tapeMarks:document.querySelectorAll('.ix-tape .mk').length,labelEls:document.querySelectorAll('.ix-labels .ix-lm').length,edgeEls:[...document.querySelectorAll('.ix-edges .ix-edge')].map(e=>e.textContent.trim())}));
check('쌍안경 이름표(출발 지점)',b.tapeMarks>0&&(b.labelEls>0||b.edgeEls.length>0),b);
await p.screenshot({path:`${dir}/bino.png`});
check('오류 없음',errs.length===0,errs);
await browser.close();await vite.close();process.exit(fail?1:0);
